const createExercise = (
  id: string,
  name: string,
  targetSets: number,
  reps: number,
  defaultRestSec: number,
  muscleGroup: ExerciseItem['muscleGroup'],
  muscleSecondary: string,
  tips: string,
): ExerciseItem => ({
  id,
  name,
  muscleGroup,
  muscleSecondary,
  targetSets,
  targetReps: reps + ' repetições',
  defaultRestSec,
  tips,
  notes: tips,
  sets: Array.from({ length: targetSets }, (_, index) => ({
    id: id + '-set-' + (index + 1),
    setNumber: index + 1,
    weightKg: 0,
    reps,
    completed: false,
  })),
});

